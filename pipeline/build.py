#!/usr/bin/env python3
"""Phase 2 pipeline CLI: labeled scan -> jas-bundle/1 folder (1.4 -> 1.5 -> 1.6).

    # synthetic phantom (the only bundle committed to Git)
    python3 -m pipeline.build --phantom --out media/models/phantom

    # a real MSD case from the shared Drive (output stays out of Git)
    export JAS_DATA_ROOT=".../My Drive/NOVA-data"
    python3 -m pipeline.build --dataset msd-liver --case liver_39 --out artifacts/liver_39
    python3 -m pipeline.build --dataset msd-liver --case liver_39 --out media/local/liver_39

Real-data output may only go under ignored folders (artifacts/, data/,
media/local/). media/local/ is still inside the media airlock, so the
board can stage it on your machine, and Git never sees it.
"""
import argparse
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE))

from pipeline import export, optimize, phantom, surfaces  # noqa: E402

IGNORED_OUT = ("artifacts", "data", "media/local")

LICENSES = {
    "synthetic": ("CC-BY-4.0 (this repository's generated fixture)",
                  "Synthetic phantom generated by pipeline/phantom.py; no patient data."),
    "msd-liver": ("CC-BY-SA-4.0",
                  "Antonelli M. et al., The Medical Segmentation Decathlon, Nat Commun 13, 4128 (2022); "
                  "Simpson A. et al., arXiv:1902.09063 (2019)."),
    "msd-hepaticvessel": ("CC-BY-SA-4.0",
                          "Antonelli M. et al., Nat Commun 13, 4128 (2022); Simpson A. et al., "
                          "arXiv:1902.09063 (2019). Hepatic vessel data: Memorial Sloan Kettering Cancer Center."),
}


def _guard_out(out, synthetic):
    out = out.resolve()
    if synthetic or HERE not in out.parents:
        return
    rel = out.relative_to(HERE).as_posix()
    if not any(rel == p or rel.startswith(p + "/") for p in IGNORED_OUT):
        raise SystemExit(f"refusing to write scan-derived output to {rel!r}: use one of "
                         f"{', '.join(IGNORED_OUT)} (no patient-derived assets in Git)")


def run(ci, out, *, with_volume, created=None, tol=None, plan=None, log=print):
    surfs = surfaces.extract_all(ci)
    opt, reports = {}, {}
    for s in surfs:
        v, f, r = optimize.optimize(s, ci.spacing, tol, plan)
        opt[s.structure_id], reports[s.structure_id] = (v, f), r
        fin = r.get("final", {})
        log(f"  {s.structure_id:16s} {s.status:7s} voxels={s.voxels:<9d} "
            f"{s.volume_ml:9.2f} ml  faces {len(s.faces)}->{fin.get('faces', 0)}  "
            f"disp {fin.get('max_displacement_mm', 0)} mm  dV {fin.get('volume_change_pct', 0)}%")
    ds = ci.provenance.get("dataset", "synthetic")
    lic, cite = LICENSES.get(ds, ("unknown", "unknown"))
    source = {"name": f"{ci.source_case} via jas-grainger pipeline",
              "url": "https://github.com/s-meher/jas-grainger",
              "license": lic,
              "modifications": "marching cubes per label in RAS+ mm; bounded Taubin smoothing and "
                               "quadric decimation gated by QA (see manifest.json validation)"}
    seg = ({"source": "synthetic ground truth", "reviewer_state": "dataset_reference"}
           if ds == "synthetic" else
           {"source": f"{ds} expert labels as distributed", "reviewer_state": "dataset_reference"})
    m = export.write_bundle(
        out, ci, surfs, opt, reports, source=source, dataset_license=lic, citation=cite,
        segmentation=seg, with_volume=with_volume, created=created,
        pipeline_config={"tolerances": {**optimize.DEFAULT_TOLERANCES, **(tol or {})},
                         "plan": {**optimize.DEFAULT_PLAN, **(plan or {})}})
    (Path(out) / "qa.json").write_text(json.dumps(reports, indent=2, default=float) + "\n")
    return m


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--phantom", action="store_true")
    src.add_argument("--case")
    ap.add_argument("--dataset", choices=["msd-liver", "msd-hepaticvessel"])
    ap.add_argument("--root", default=os.environ.get("JAS_DATA_ROOT"))
    ap.add_argument("--out", required=True)
    ap.add_argument("--with-volume", action="store_true", help="also write volume.nrrd")
    ap.add_argument("--created", help="fixed ISO timestamp (reproducible fixture)")
    a = ap.parse_args(argv)
    out = Path(a.out)
    if not out.is_absolute():
        out = Path.cwd() / out
    _guard_out(out, a.phantom)
    if a.phantom:
        ci = phantom.build()
        with_volume = True
    else:
        if not (a.dataset and a.root):
            ap.error("--case needs --dataset and --root/JAS_DATA_ROOT")
        from pipeline.nifti_adapter import load_nifti_pair   # placeholder for 1.2
        d = Path(a.root).expanduser() / a.dataset / a.case
        ci = load_nifti_pair(d / "image.nii.gz", d / "label.nii.gz", a.dataset, a.case,
                             with_image=a.with_volume)
        with_volume = a.with_volume
    print(f"{ci.source_case}: shape {ci.labels.shape}, spacing "
          f"{tuple(round(s, 3) for s in ci.spacing)} mm")
    m = run(ci, out, with_volume=with_volume, created=a.created)
    print(f"wrote {out} revision {m['revision'][:12]}")
    from pipeline.verify_bundle import verify
    errs = verify(out)
    for e in errs:
        print("ERROR", e)
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
